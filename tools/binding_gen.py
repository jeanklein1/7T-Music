def main():
    ap = argparse.ArgumentParser(description="LOOM_1 \u2014 the one table's instrument.")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--bootstrap", action="store_true",
                   help="parse the tree, print a schema module to stdout")
    g.add_argument("--check", action="store_true",
                   help="diff tree against schema, verify emitters and witnesses")
    g.add_argument("--write", nargs="?", const="all",
                   choices=("registry", "inc", "all"), metavar="TARGET",
                   help="emit binding_registry.hpp and/or binding_surface.gen.inc "
                        "(registry | inc | all; default all). U2 flips the "
                        "registry alone; U3 flips the state.hpp blocks.")
    g.add_argument("--write-wgsl", metavar="PATH",
                   help="renumber the declaration sites of the file at PATH")
    g.add_argument("--plan", action="store_true",
                   help="derive the LOOM_2 recut plan into audit/RECUT_PLAN.md")
    args = ap.parse_args()

    if args.plan:
        P = plan(args)
        emit_plan(P, PLAN_OUT)
        print("binding_gen --plan")
        print("")
        print("  families: %d pipelines over %d families (+ FADE + 2 family-less)"
              % (len(P["fam_of_pipe"]),
                 len({f for f in P["fam_of_pipe"].values()
                      if f in RECUT_FAMILIES})))
        print("  placement: %d slots placed, %d STOPs, %d findings"
              % (len(P["new_slot"]), len(P["stops"]), len(P["findings"])))
        print("  layouts: %d planned (+EMPTY at %s); seats %d -> %d"
              % (len(P["new_layouts"]),
                 ",".join(str(i) for i in sorted(P["empty_indices"])) or "-",
                 len(P["schema"].SEATS),
                 sum(len(v) for v in P["new_layouts"].values())))
        for s_ in P["stops"]:
            print("  STOP %s" % s_)
        print("")
        print("  wrote %s" % os.path.relpath(PLAN_OUT, REPO))
        return 1 if P["stops"] else 0

    if args.bootstrap:
        print_schema(capture_tree())
        return 0
    if args.check:
        return check(args)
    if args.write:
        schema = load_schema()
        if args.write in ("registry", "all"):
            write_file(REGISTRY_HPP, emit_registry(schema, with_notice=True))
            print("wrote %s" % os.path.relpath(REGISTRY_HPP, REPO))
        if args.write in ("inc", "all"):
            write_file(GEN_INC, emit_gen_inc(schema))
            print("wrote %s" % os.path.relpath(GEN_INC, REPO))
        return 0
    if args.write_wgsl:
        schema = load_schema()
        raw = BL.read(args.write_wgsl)
        write_file(args.write_wgsl, rewrite_wgsl(schema, raw))
        print("wrote %s" % args.write_wgsl)
        return 0
    return 2


