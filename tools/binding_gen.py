def load_schema():
    if not os.path.exists(SCHEMA_PATH):
        stop("tools/binding_schema.py does not exist \u2014 run --bootstrap "
             "and review its output into place")
    return _load("binding_schema")


def diff_relation(name, tree_rel, schema_rel, out):
    """Symbol-keyed, both directions."""
    bad = 0
    tk, sk = set(tree_rel), set(schema_rel)
    for k in sorted(tk - sk, key=repr):
        out.append("  %s: %r in tree, absent from schema" % (name, k))
        bad += 1
    for k in sorted(sk - tk, key=repr):
        out.append("  %s: %r in schema, absent from tree" % (name, k))
        bad += 1
    for k in sorted(tk & sk, key=repr):
        t, s = tree_rel[k], schema_rel[k]
        if isinstance(t, dict) and isinstance(s, dict):
            for col in sorted(set(t) | set(s)):
                if t.get(col) != s.get(col):
                    out.append("  %s[%r].%s: tree %r, schema %r"
                               % (name, k, col, t.get(col), s.get(col)))
                    bad += 1
        elif t != s:
            out.append("  %s[%r]: tree %r, schema %r" % (name, k, t, s))
            bad += 1
    return bad


def ledger_cardinalities():
    led = BL.read(LEDGER_MD)
    m1 = re.search(r"(\d+) module-scope declarations over (\d+) `\(group, binding\)` slots", led)
    m2 = re.search(r"One row per `\(bind group layout, entry index\)`, (\d+) rows over (\d+) layouts", led)
    m3 = re.search(r"(\d+) bind groups over (\d+) layouts, every one a bijection", led)
    m4 = re.search(r"(\d+) pipelines: \d+ with exactly one call shape", led)
    if not (m1 and m2 and m3 and m4):
        stop("the ledger does not state its counts \u2014 S-1 cannot read its authority")
    return {"decls": int(m1.group(1)), "slots": int(m1.group(2)),
            "seats": int(m2.group(1)), "layouts": int(m2.group(2)),
            "groups": int(m3.group(1)), "pipelines": int(m4.group(1))}


def table_h_sites():
    led = BL.read(LEDGER_MD)
    rows = []
    for m in re.finditer(r"^\| `([^`]+)` \| ([\w ]+) \| `([^`]+)` \| \d+ \| ([^|]+) \|",
                        led, re.M):
        trig = [t.strip().strip("`") for t in m.group(4).split(",")]
        rows.append({"symbol": m.group(1), "kind": m.group(2).strip(),
                     "file": m.group(3), "triggers": trig})
    return rows


def check(args):
    tree = capture_tree()
    schema = load_schema()
    problems = []
    print("binding_gen --check")
    print("")
    print("RELATIONS (tree vs schema, both directions)")
    n = 0
    for name in ("DECLS", "REGISTRY", "SEATS", "LAYOUTS", "GROUPS",
                 "PIPELINES"):
        lines = []
        n += diff_relation(name, tree[name], getattr(schema, name), lines)
        print("  %-9s %4d rows  %s"
              % (name, len(tree[name]), "agree" if not lines else "MISMATCH"))
        for ln in lines[:40]:
            print("  " + ln)
        problems.extend(lines)
    for name in ("REGISTRY_FILE_BANNER", "REGISTRY_NAMESPACES",
                 "REGISTRY_INVARIANTS"):
        same = tree[name] == getattr(schema, name)
        print("  %-22s %s" % (name, "agree" if same else "MISMATCH"))
        if not same:
            problems.append("%s differs" % name)

    print("")
    print("EMIT TARGETS (schema -> bytes vs disk)")
    disk = BL.read(REGISTRY_HPP)
    flipped = NOTICE in disk.split("\n", 1)[0]
    want = emit_registry(schema, with_notice=flipped)
    tag = "generated" if flipped else "target not yet generated; pre-flip equivalence"
    same = want == disk
    print("  binding_registry.hpp: %s \u2014 %s" % (tag, "OK" if same else "DIVERGES"))
    if not same:
        for i, (a, b_) in enumerate(zip(disk.split("\n"), want.split("\n")), 1):
            if a != b_:
                print("    first divergence at line %d:\n      disk: %r\n      emit: %r"
                      % (i, a, b_))
                break
        problems.append("registry emission diverges from disk")
    if os.path.exists(GEN_INC):
        same = emit_gen_inc(schema) == BL.read(GEN_INC)
        print("  binding_surface.gen.inc: generated \u2014 %s"
              % ("OK" if same else "DIVERGES"))
        if not same:
            problems.append("gen.inc emission diverges from disk")
    else:
        print("  binding_surface.gen.inc: target not yet generated")

    print("")
    print("WITNESSES")
    card = ledger_cardinalities()
    slots = len({(d["group"], d["binding"]) for d in schema.DECLS.values()})
    got = (len(schema.DECLS), slots, len(schema.SEATS), len(schema.LAYOUTS),
           len(schema.GROUPS), len(schema.PIPELINES))
    wantc = (card["decls"], card["slots"], card["seats"], card["layouts"],
             card["groups"], card["pipelines"])
    ok = got == wantc
    print("  [%s] S-1  schema cardinalities equal the ledger's: %s vs %s"
          % ("PASS" if ok else "FAIL",
             "/".join(str(x) for x in got), "/".join(str(x) for x in wantc)))
    if not ok:
        problems.append("S-1 cardinality mismatch")

    # S-2: the defended text survived transcription. For every Table H
    # site in the registry or the layout blocks, each of its triggers
    # must match the schema's concatenated prose for that relation.
    prose_reg = "\n".join(
        ["\n".join(schema.REGISTRY_FILE_BANNER)] +
        ["\n".join(b["banner"]) for ns in schema.REGISTRY_NAMESPACES
         for b in ns["bands"] if b["banner"]] +
        ["\n".join(ns["banner"]) for ns in schema.REGISTRY_NAMESPACES] +
        [r["text"] for r in schema.REGISTRY.values()] +
        ["\n".join(schema.REGISTRY_INVARIANTS)])
    prose_seats = "\n".join(
        ["\n".join(s["prose"]) for s in schema.SEATS.values() if s["prose"]] +
        [t for s in schema.SEATS.values() for t in s["trailing"].values()] +
        ["\n".join(r["prose"]) for r in schema.LAYOUTS.values() if r["prose"]])
    trig_pat = dict(BL.TRIGGERS)
    missing = []
    checked = 0
    for site in table_h_sites():
        if "binding_registry.hpp" in site["file"] and site["kind"] in (
                "file", "registry constant"):
            hay = prose_reg
        elif "state.hpp" in site["file"] and site["kind"] in (
                "layout", "layout entry"):
            hay = prose_seats
        else:
            continue
        checked += 1
        for t in site["triggers"]:
            pat = trig_pat.get(t)
            if pat is None or not re.search(
                    pat, hay, re.I if t != "law-ref" else 0):
                missing.append("%s (%s): trigger %s not found"
                               % (site["symbol"], site["kind"], t))
    ok = not missing
    print("  [%s] S-2  %d Table H sites in the transcribed mirrors; every "
          "trigger matches the schema's prose%s"
          % ("PASS" if ok else "FAIL", checked,
             "" if ok else " \u2014 MISSING: " + "; ".join(missing)))
    if not ok:
        problems.append("S-2 trigger loss")

    # S-3 (in memory): renumber with unchanged numbers is the identity.
    raw = BL.read(WORLD_WGSL)
    ok = rewrite_wgsl(schema, raw) == raw
    print("  [%s] S-3  --write-wgsl round-trip with unchanged numbers is "
          "the identity on world.wgsl" % ("PASS" if ok else "FAIL"))
    if not ok:
        problems.append("S-3 wgsl round-trip diverges")

    print("")
    if problems:
        print("STOP \u2014 %d problem(s); the schema and the tree disagree, or "
              "an emitter diverges." % len(problems))
        return 1
    print("--check: all relations agree, all witnesses pass.")
    return 0


