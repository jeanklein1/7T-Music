def write_file(path, text):
    """The G2-eol pattern: pinned writer, byte-level read-back."""
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    bx = BL.verify_bytes(path)
    if bx["crlf"] or bx["cr"] or bx["bom"] or not bx["trailing"]:
        stop("encoding read-back failed on %s: %r" % (path, bx))
    return bx


