def emit_registry(schema, with_notice=True):
    L = []
    L.append("#pragma once" + ("  // " + NOTICE if with_notice else ""))
    L.extend(schema.REGISTRY_FILE_BANNER)
    L.append("#include <cstdint>")
    L.append("")
    L.append("namespace t7 {")
    L.append("    namespace the_board {")
    L.append("        namespace bind {")
    for ns in schema.REGISTRY_NAMESPACES:
        L.append("")
        for ln in ns["banner"]:
            L.append(("            " + ln) if ln else "")
        L.append("            namespace %s {" % ns["name"])
        for band in ns["bands"]:
            L.extend([""] * band["gap_before"])
            if band["banner"]:
                for ln in band["banner"]:
                    L.append(("                " + ln) if ln else "")
            for cname in band["constants"]:
                L.append("                " + schema.REGISTRY[cname]["text"])
        L.append("            } // namespace %s" % ns["name"])
    L.append("")
    for ln in schema.REGISTRY_INVARIANTS:
        L.append(("            " + ln) if ln else "")
    L.append("")
    L.append("        } // namespace bind")
    L.append("    } // namespace the_board")
    L.append("} // namespace t7")
    return "\n".join(L) + "\n"


def _slot_const(schema, decl_sym):
    """DECL symbol -> the registry constant naming its slot."""
    d = schema.DECLS[decl_sym]
    prim = d["alias_of"] or decl_sym
    ns = "g%d" % d["group"]
    row = schema.REGISTRY.get(prim)
    if row is None or row["namespace"] != ns or row["binding"] != d["binding"]:
        stop("no registry constant for decl %s at (%d, %d)"
             % (decl_sym, d["group"], d["binding"]))
    return "bind::%s::%s" % (ns, prim)


def _seat_type_lines(schema, seat, ind):
    """The type-specific statements of one layout seat."""
    d = schema.DECLS[seat["decl"]]
    fact = d["cpp"]
    i = seat_index = seat["_index"]
    t = seat.get("trailing", {})

    def line(field, value):
        c = t.get(field)
        return "%sentries[%d].%s = %s;%s" % (ind, i, field, value,
                                             ("  " + c) if c else "")
    out = []
    if fact[0] == "buffer":
        out.append(line("buffer.type", "wgpu::BufferBindingType::" + fact[1]))
        if seat["has_dynamic_offset"]:
            out.append(line("buffer.hasDynamicOffset", "true"))
        if seat["min_binding_size"]:
            out.append(line("buffer.minBindingSize", seat["min_binding_size"]))
    elif fact[0] == "sampler":
        out.append(line("sampler.type", "wgpu::SamplerBindingType::" + fact[1]))
    elif fact[0] == "texture":
        out.append(line("texture.sampleType", "wgpu::TextureSampleType::" + fact[1]))
        out.append(line("texture.viewDimension",
                        "wgpu::TextureViewDimension::" + fact[2]))
    else:
        out.append(line("storageTexture.access",
                        "wgpu::StorageTextureAccess::" + fact[1]))
        out.append(line("storageTexture.format", "wgpu::TextureFormat::" + fact[2]))
        out.append(line("storageTexture.viewDimension",
                        "wgpu::TextureViewDimension::" + fact[3]))
    return out


def emit_gen_inc(schema, class_indent="            "):
    """binding_surface.gen.inc \u2014 three GPUState member functions.
    Canonical statement order: seats index-ascending, fields binding /
    visibility / type facts; visibility operands in V|F|C order."""
    ind0 = class_indent                  # member-function signature
    ind1 = ind0 + "    "                 # function body / block braces
    ind2 = ind1 + "    "                 # statements inside a block
    L = []
    bar = "// " + "\u2500" * 68
    L.append(ind0 + bar)
    L.append(ind0 + "// " + NOTICE)
    L.append(ind0 + "// The binding-surface creation blocks, emitted from the schema's")
    L.append(ind0 + "// SEATS / LAYOUTS / GROUPS relations. Seat prose travels from the")
    L.append(ind0 + "// schema verbatim. Statement order is canonical: seats ascend by")
    L.append(ind0 + "// entry index; visibility operands are in Vertex/Fragment/Compute")
    L.append(ind0 + "// order.")
    L.append(ind0 + bar)

    def prose(lines_, ind):
        return [(ind + ln) if ln else "" for ln in (lines_ or [])]

    # ─── the 25 layouts ───────────────────────────────────────────────
    L.append("")
    L.append(ind0 + "bool create_binding_layouts() {")
    seats_by_layout = {}
    for (member, idx), s in schema.SEATS.items():
        seats_by_layout.setdefault(member, {})[idx] = dict(s, _index=idx)
    for member, row in schema.LAYOUTS.items():
        seats = seats_by_layout.get(member, {})
        L.extend(prose(row.get("prose"), ind1))
        L.append(ind1 + "{")
        L.append(ind2 + "std::array<wgpu::BindGroupLayoutEntry, %d> entries{};"
                 % len(seats))
        for idx in sorted(seats):
            s = seats[idx]
            L.append("")
            L.extend(prose(s.get("prose"), ind2))
            t = s.get("trailing", {})
            c = t.get("binding")
            L.append("%sentries[%d].binding = %s;%s"
                     % (ind2, idx, _slot_const(schema, s["decl"]),
                        ("  " + c) if c else ""))
            vis = " | ".join(VIS_EMIT[v] for v in s["visibility"].split("|"))
            c = t.get("visibility")
            L.append("%sentries[%d].visibility = %s;%s"
                     % (ind2, idx, vis, ("  " + c) if c else ""))
            L.extend(_seat_type_lines(schema, s, ind2))
        L.append("")
        L.append(ind2 + "wgpu::BindGroupLayoutDescriptor desc{};")
        L.append(ind2 + 'desc.label = "%s";' % row["label"])
        L.append(ind2 + "desc.entryCount = entries.size();")
        L.append(ind2 + "desc.entries = entries.data();")
        L.append(ind2 + "%s = device_.CreateBindGroupLayout(&desc);" % member)
        L.append(ind2 + "if (!%s) return false;" % member)
        L.append(ind1 + "}")
    L.append(ind1 + "return true;")
    L.append(ind0 + "}")

    # ─── the bind groups ──────────────────────────────────────────────
    def group_block(key, row, ind_a, ind_b, tail):
        out = []
        out.extend(prose(row.get("prose"), ind_a))
        opener = (ind_a + "{") if key != "build_render_entity_group" else (
            ind_a + "auto build_render_entity_group = [&](const char* label, "
                    "uint32_t listOff, uint32_t listBytes) -> wgpu::BindGroup {")
        out.append(opener)
        entries = row["entries"]
        out.append(ind_b + "std::array<wgpu::BindGroupEntry, %d> entries{};"
                   % len(entries))
        for lc in row.get("local_constants", []):
            out.append(ind_b + lc)
        for idx in sorted(entries):
            e = entries[idx]
            out.append("")
            out.extend(prose(e.get("prose"), ind_b))
            t = e.get("trailing", {})
            c = t.get("binding")
            out.append("%sentries[%d].binding = %s;%s"
                       % (ind_b, idx, _slot_const(schema, e["decl"]),
                          ("  " + c) if c else ""))
            d = schema.DECLS[e["decl"]]
            field = {"buffer": "buffer", "sampler": "sampler",
                     "texture": "textureView",
                     "storageTexture": "textureView"}[d["cpp"][0]]
            c = t.get(field)
            out.append("%sentries[%d].%s = %s;%s"
                       % (ind_b, idx, field, e["backing"],
                          ("  " + c) if c else ""))
            if e.get("offset_expr") is not None:
                c = t.get("offset")
                out.append("%sentries[%d].offset = %s;%s"
                           % (ind_b, idx, e["offset_expr"],
                              ("  " + c) if c else ""))
            if e.get("size_expr") is not None:
                c = t.get("size")
                out.append("%sentries[%d].size = %s;%s"
                           % (ind_b, idx, e["size_expr"],
                              ("  " + c) if c else ""))
        out.append("")
        out.append(ind_b + "wgpu::BindGroupDescriptor desc{};")
        if row["label_param"]:
            out.append(ind_b + "desc.label = label;")
        else:
            out.append(ind_b + 'desc.label = "%s";' % row["label"])
        out.append(ind_b + "desc.layout = %s;" % row["layout"])
        out.append(ind_b + "desc.entryCount = entries.size();")
        out.append(ind_b + "desc.entries = entries.data();")
        out.extend(tail)
        return out

    L.append("")
    L.append(ind0 + "bool create_binding_groups_boot() {")
    for key, row in schema.GROUPS.items():
        if row["cadence"] == "rebuild":
            continue
        if row["cadence"] == "builder":
            L.extend(group_block(key, row, ind1, ind2, [
                ind2 + "return device_.CreateBindGroup(&desc);",
                ind1 + "};"]))
            for iv in row["invocations"]:
                L.append(ind1 + '%s = build_render_entity_group("%s", %s, %s);'
                         % (iv["member"], iv["label"], iv["offset_arg"],
                            iv["size_arg"]))
            L.append(ind1 + "if (%s) return false;"
                     % " || ".join("!" + iv["member"] for iv in row["invocations"]))
        else:
            L.extend(group_block(key, row, ind1, ind2, [
                ind2 + "%s = device_.CreateBindGroup(&desc);" % key,
                ind2 + "if (!%s) return false;" % key,
                ind1 + "}"]))
    L.append(ind1 + "return true;")
    L.append(ind0 + "}")

    L.append("")
    L.append(ind0 + "// Callable at boot and at the exhibition rebuild \u2014 the one bind")
    L.append(ind0 + "// group re-made after boot, against the exhibition read view.")
    L.append(ind0 + "bool create_gallery_texture_group() {")
    for key, row in schema.GROUPS.items():
        if row["cadence"] != "rebuild":
            continue
        L.extend(group_block(key, row, ind1, ind2, [
            ind2 + "%s = device_.CreateBindGroup(&desc);" % key,
            ind2 + "if (!%s) return false;" % key,
            ind1 + "}"]))
    L.append(ind1 + "return true;")
    L.append(ind0 + "}")
    return "\n".join(L) + "\n"


def rewrite_wgsl(schema, raw):
    """Symbol-anchored renumber of the 98 declaration sites: only the
    @group / @binding integers change; prose, scatter, spacing stay."""
    out = raw
    for sym, row in schema.DECLS.items():
        pat = re.compile(
            r"(@group\()(\d+)(\)\s*@binding\()(\d+)(\)\s*var(?:<[^>]*>)?\s+%s\s*:)"
            % re.escape(sym))
        ms = list(pat.finditer(out))
        if len(ms) != 1:
            stop("write-wgsl anchor for %r matches %d times; site(s): %s"
                 % (sym, len(ms),
                    "; ".join(MC.norm(m.group(0)) for m in ms) or "none"))
        out = pat.sub(lambda m: "%s%d%s%d%s" % (m.group(1), row["group"],
                                                m.group(3), row["binding"],
                                                m.group(5)), out, count=1)
    return out


