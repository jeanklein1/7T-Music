def _fmt(v):
    if isinstance(v, dict):
        return "{" + ", ".join("%s: %s" % (_fmt(k), _fmt(x))
                               for k, x in v.items()) + "}"
    if isinstance(v, (list, tuple)):
        inner = ", ".join(_fmt(x) for x in v)
        return ("(" + inner + ("," if len(v) == 1 else "") + ")"
                if isinstance(v, tuple) else "[" + inner + "]")
    return repr(v)


