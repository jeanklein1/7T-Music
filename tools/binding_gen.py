def _dedent_uniform(lines, where):
    """Strip one uniform indentation from a verbatim line group."""
    pad = None
    for ln in lines:
        if not ln.strip():
            continue
        p = len(ln) - len(ln.lstrip(" "))
        pad = p if pad is None else min(pad, p)
    pad = pad or 0
    for ln in lines:
        if ln.strip() and (len(ln) - len(ln.lstrip(" "))) < pad:
            stop("ragged indentation in %s: %r" % (where, ln))
    return [ln[pad:] if ln.strip() else "" for ln in lines]


def segment_registry():
    """binding_registry.hpp -> file banner, namespace/band structure,
    constants with their verbatim lines, the invariants block."""
    raw = BL.read(REGISTRY_HPP)
    lines = raw.split("\n")
    if lines and lines[-1] == "":
        lines = lines[:-1]
    i = 0
    if not lines[i].startswith("#pragma once"):
        stop("registry does not start with #pragma once: %r" % lines[i])
    i += 1
    banner = []
    while lines[i].startswith("//"):
        banner.append(lines[i])
        i += 1
    for want in ("#include <cstdint>", "", "namespace t7 {",
                 "    namespace the_board {", "        namespace bind {"):
        if lines[i] != want:
            stop("registry skeleton: expected %r, found %r" % (want, lines[i]))
        i += 1

    consts = {}
    namespaces = []
    while True:
        # a namespace section: blank, banner block, open, items, close
        if lines[i] != "":
            break
        i += 1
        ns_banner = []
        while lines[i].lstrip().startswith("//"):
            ns_banner.append(lines[i])
            i += 1
        m = re.fullmatch(r"\s*namespace (g\d) \{", lines[i])
        if not m:
            stop("registry skeleton: expected namespace open, found %r" % lines[i])
        name = m.group(1)
        i += 1
        bands = []
        cur = None
        gap = 0
        while not re.fullmatch(r"\s*\} // namespace %s" % name, lines[i]):
            ln = lines[i]
            if ln.strip() == "":
                gap += 1
                i += 1
                continue
            if ln.lstrip().startswith("//"):
                blk = []
                while lines[i].lstrip().startswith("//"):
                    blk.append(lines[i])
                    i += 1
                cur = {"gap_before": gap,
                       "banner": _dedent_uniform(blk, "band banner in " + name),
                       "constants": []}
                bands.append(cur)
                gap = 0
                continue
            cm = re.fullmatch(
                r"\s*inline constexpr uint32_t (\w+)\s+= (\d+);(?:\s*// ?(.*))?",
                ln)
            if not cm:
                stop("registry: unparseable line in %s: %r" % (name, ln))
            if gap:
                stop("registry: blank line inside a constant run before %r "
                     "\u2014 the band model cannot carry it" % ln)
            if cur is None:
                cur = {"gap_before": 0, "banner": None, "constants": []}
                bands.append(cur)
            cur["constants"].append(cm.group(1))
            consts[cm.group(1)] = {
                "namespace": name,
                "binding": int(cm.group(2)),
                "trailing_comment": cm.group(3) if cm.group(3) is not None else None,
                "text": ln.strip(),
            }
            i += 1
        i += 1
        namespaces.append({"name": name,
                           "banner": _dedent_uniform(ns_banner,
                                                     "banner of " + name),
                           "bands": bands})
        if not (lines[i] == "" and lines[i + 1].lstrip().startswith("//")
                and "namespace g" not in lines[i + 1]):
            # not another namespace section: fall through to invariants
            if not re.fullmatch(r"\s*namespace g\d \{", lines[i + 1].strip() + " {") :
                pass
        # peek: another namespace?
        j = i
        if lines[j] == "":
            k = j + 1
            while k < len(lines) and lines[k].lstrip().startswith("//"):
                k += 1
            if k < len(lines) and re.fullmatch(r"\s*namespace g\d \{", lines[k]):
                continue
        break

    if lines[i] != "":
        stop("registry skeleton: expected blank before invariants, found %r"
             % lines[i])
    i += 1
    inv = []
    while lines[i].strip() != "":
        inv.append(lines[i])
        i += 1
    i += 1
    for want in ("        } // namespace bind", "    } // namespace the_board",
                 "} // namespace t7"):
        if lines[i] != want:
            stop("registry skeleton: expected %r, found %r" % (want, lines[i]))
        i += 1
    if i != len(lines):
        stop("registry skeleton: %d trailing line(s) after the closes"
             % (len(lines) - i))
    return {"file_banner": banner, "namespaces": namespaces,
            "constants": consts,
            "invariants": _dedent_uniform(inv, "invariants block")}


def _prose_above(lines, idx):
    """Comment runs (with internal blanks) directly above lines[idx],
    walking up until code. Returns verbatim lines, blank-trimmed."""
    out = []
    j = idx - 1
    while j >= 0:
        s = lines[j].strip()
        if s == "" or s.startswith("//"):
            out.append(lines[j])
            j -= 1
        else:
            break
    out.reverse()
    while out and out[0].strip() == "":
        out.pop(0)
    while out and out[-1].strip() == "":
        out.pop()
    if not any(x.strip() for x in out):
        return None
    return _dedent_uniform(out, "prose above line %d" % (idx + 1))


class BlockCapture:
    """Prose and trailing comments for one state.hpp creation block."""
    __slots__ = ("exterior", "seat_prose", "trailing", "min_binding",
                 "local_constants", "start_line", "brace_line")


def capture_state_blocks(kind_re, create_token):
    """For each block (file order): exterior prose above the opening
    brace, per-seat leading prose, per-statement trailing comments,
    minBindingSize expressions, in-block constants. All verbatim."""
    raw = BL.read(STATE_HPP)
    src = BL.strip_cpp_comments(raw)
    rawlines = raw.split("\n")
    out = []
    for m in re.finditer(
            r"std::array<\s*wgpu::" + kind_re + r"\s*,\s*(\d+)\s*>\s*(\w+)\s*\{\s*\}\s*;",
            src):
        tail = src.find(create_token, m.end())
        end = src.find(";", tail) + 1
        cap = BlockCapture()
        cap.start_line = BL.line_of(src, m.start())
        # the opening brace of the block's scope, walking up raw lines
        bi = cap.start_line - 2
        while bi >= 0 and rawlines[bi].strip() in ("", "{"):
            if rawlines[bi].strip() == "{":
                break
            bi -= 1
        if bi < 0 or rawlines[bi].strip() != "{":
            # the builder block opens with the lambda header, not a bare {
            hm = re.search(r"->\s*wgpu::BindGroup\s*\{\s*$", rawlines[cap.start_line - 2])
            if hm:
                bi = cap.start_line - 2
                while bi >= 0 and "auto build_render_entity_group" not in rawlines[bi]:
                    bi -= 1
            else:
                stop("state.hpp block at line %d has no enclosing '{' line"
                     % cap.start_line)
        cap.brace_line = bi + 1
        cap.exterior = _prose_above(rawlines, bi)
        cap.seat_prose = {}
        cap.trailing = {}
        cap.min_binding = {}
        cap.local_constants = []
        block_src = src[m.start():end]
        for e in re.finditer(r"entries\[(\d+)\]\.([\w.]+)\s*=", block_src):
            idx = int(e.group(1))
            field = e.group(2)
            ln = BL.line_of(src, m.start() + e.start())
            if field == "binding":
                p = _prose_above(rawlines, ln - 1)
                if p:
                    cap.seat_prose[idx] = p
            tm = re.match(r".*;\s+(// .*)$", rawlines[ln - 1])
            if tm:
                cap.trailing[(idx, field)] = tm.group(1)
            if field == "buffer.minBindingSize":
                vm = re.search(r"=\s*([^;]+);", rawlines[ln - 1])
                cap.min_binding[idx] = vm.group(1).strip()
        for cm_ in re.finditer(r"static constexpr uint32_t[^;]+;", block_src):
            a, b_ = MC.tight_span(block_src, cm_.start(), cm_.end())
            cap.local_constants.append(MC.norm(raw[m.start() + a:m.start() + b_]))
        out.append(cap)
    return out


def resolve_seat_decl(entry, slots):
    """Seat -> DECL symbol, by access compatibility; this is what makes
    the vp_data/fc_vp aliased slot representable. Primary wins ties."""
    grp = int(entry.registry_ns[1])
    cands = slots.get((grp, entry.binding_number), [])

    def compat(d):
        if entry.kind == "buffer":
            if d.address_space == "uniform":
                return entry.access == "Uniform"
            if d.address_space == "storage":
                return ((entry.access == "Storage" and d.wgsl_access == "read_write")
                        or (entry.access == "ReadOnlyStorage" and d.wgsl_access == "read"))
            return False
        return d.address_space == "handle"

    ok = [d for d in cands if compat(d)]
    if not ok:
        stop("no access-compatible declaration for seat %s entries[%d] (%s %s)"
             % (entry.layout_label, entry.entry_index, entry.kind, entry.access))
    ok.sort(key=lambda d: d.line)
    return ok[0].symbol


def capture_tree():
    """The whole tree, parsed into the schema module's exact shape."""
    w = BL.Witnesses()
    registry_consts = BL.parse_registry(w)
    layouts = BL.parse_layouts(w, registry_consts)
    b = BL.phase_0b(w)
    c = BL.phase_0c(w, layouts, b)
    groups, invokes = MC.parse_groups(w)
    bad = w.failures()
    if bad:
        stop("imported parsers report failures: %s"
             % "; ".join(t for t, _, _ in bad))

    # ─── DECLS ────────────────────────────────────────────────────────
    decls = {}
    primary = {}
    for d in sorted(b["decls"], key=lambda d: d.line):
        slot = (d.group, d.binding)
        decls[d.symbol] = {
            "group": d.group,
            "binding": d.binding,
            "address_space": d.address_space,
            "access": d.wgsl_access if d.address_space == "storage" else None,
            "store_type": d.wgsl_type,
            "alias_of": primary.get(slot),
        }
        primary.setdefault(slot, d.symbol)

    # Per-decl C++ seat-type facts. Filtering vs NonFiltering and Float
    # vs UnfilterableFloat are C++-side choices no WGSL spelling caries,
    # so they are schema columns; one value per DECL, asserted here.
    cpp = {}
    for L in layouts:
        for e in L["entries"]:
            sym = resolve_seat_decl(e, b["slots"])
            if e.kind == "buffer":
                fact = ("buffer", e.access)
            elif e.kind == "sampler":
                fact = ("sampler", e.access)
            elif e.kind == "texture":
                s_, dim = e.access.split("/")
                fact = ("texture", s_, dim)
            else:
                a_, f_, dim = e.access.split("/")
                fact = ("storageTexture", a_, f_, dim)
            if sym in cpp and cpp[sym] != fact:
                stop("decl %s carries two seat-type facts: %r vs %r"
                     % (sym, cpp[sym], fact))
            cpp[sym] = fact
    for sym, fact in cpp.items():
        decls[sym]["cpp"] = fact
    for sym in decls:
        decls[sym].setdefault("cpp", None)   # never bound by any layout

    # ─── REGISTRY ─────────────────────────────────────────────────────
    seg = segment_registry()
    for name, row in seg["constants"].items():
        if registry_consts.get((row["namespace"], name)) != row["binding"]:
            stop("registry segmentation disagrees with parse_registry at %s" % name)

    # ─── SEATS ────────────────────────────────────────────────────────
    layout_caps = capture_state_blocks(r"BindGroupLayoutEntry",
                                       "CreateBindGroupLayout")
    if len(layout_caps) != len(layouts):
        stop("layout capture count %d != parsed layouts %d"
             % (len(layout_caps), len(layouts)))
    seats = {}
    for L, cap in zip(layouts, layout_caps):
        for e in L["entries"]:
            tr = {f: t for (i, f), t in cap.trailing.items() if i == e.entry_index}
            seats[(L["member"], e.entry_index)] = {
                "decl": resolve_seat_decl(e, b["slots"]),
                "visibility": "|".join(e.vis_declared),
                "has_dynamic_offset": e.has_dynamic_offset,
                "min_binding_size": cap.min_binding.get(e.entry_index),
                "prose": cap.seat_prose.get(e.entry_index),
                "trailing": tr,
            }

    # ─── LAYOUTS ──────────────────────────────────────────────────────
    acc = MC.accessor_map()
    layouts_rel = {}
    for L, cap in zip(layouts, layout_caps):
        a_ = acc.get(L["member"], [])
        if len(a_) != 1:
            stop("layout %s resolves to %d accessors" % (L["member"], len(a_)))
        layouts_rel[L["member"]] = {"label": L["label"], "accessor": a_[0],
                                    "prose": cap.exterior}

    # ─── GROUPS ───────────────────────────────────────────────────────
    group_caps = capture_state_blocks(r"BindGroupEntry", "CreateBindGroup(")
    if len(group_caps) != len(groups):
        stop("group capture count %d != parsed groups %d"
             % (len(group_caps), len(groups)))
    by_member = {L["member"]: L for L in layouts}
    groups_rel = {}
    for g, cap in zip(groups, group_caps):
        lay = by_member.get(g["layout_member"])
        if lay is None:
            stop("group %r: layout %r not parsed" % (g["label"], g["layout_member"]))
        seat_by_const = {e.binding_const: e for e in lay["entries"]}
        entries = {}
        for e in g["entries"]:
            le = seat_by_const.get(e["binding"])
            if le is None or le.entry_index != e["index"]:
                stop("group %r entries[%d] (%s) does not align with layout %s"
                     % (g["label"], e["index"], e["binding"], lay["label"]))
            tr = {f: t for (i, f), t in cap.trailing.items() if i == e["index"]}
            entries[e["index"]] = {
                "decl": resolve_seat_decl(le, b["slots"]),
                "backing": e["backing"],
                "size_expr": e.get("size"),
                "offset_expr": e.get("offset"),
                "prose": cap.seat_prose.get(e["index"]),
                "trailing": tr,
            }
        if g["member"] is None:
            key = "build_render_entity_group"
            cadence = "builder"
        elif g["desc_var"] != "desc":
            key = g["member"]
            cadence = "rebuild"
        else:
            key = g["member"]
            cadence = "boot"
        groups_rel[key] = {
            "label": None if g["param_label"] else g["label"],
            "label_param": g["param_label"],
            "layout": g["layout_member"],
            "cadence": cadence,
            "local_constants": cap.local_constants,
            "prose": cap.exterior,
            "entries": entries,
        }
    if "build_render_entity_group" in groups_rel:
        groups_rel["build_render_entity_group"]["invocations"] = [
            {"member": iv["member"], "label": iv["label"],
             "offset_arg": iv["offset_arg"], "size_arg": iv["size_arg"]}
            for iv in invokes]

    # ─── PIPELINES ────────────────────────────────────────────────────
    ec = c["entry_const"]
    pipelines_rel = {}
    for p in c["pipelines"]:
        pipelines_rel[p.member] = {
            "label": p.label,
            "kind": p.kind,
            "layouts": list(p.group_layouts),
            "vs": ec.get(p.vs_entry) if p.vs_entry else None,
            "fs": ec.get(p.fs_entry) if p.fs_entry else None,
            "cs": ec.get(p.cs_entry) if p.cs_entry else None,
            "vertex_buffers": p.vertex_buffer_count,
            "vertex_attributes": p.vertex_attribute_count,
            "color_targets": p.color_target_count,
            "roster_gate": p.roster_gate,
        }

    return {
        "DECLS": decls,
        "REGISTRY": seg["constants"],
        "REGISTRY_FILE_BANNER": seg["file_banner"],
        "REGISTRY_NAMESPACES": seg["namespaces"],
        "REGISTRY_INVARIANTS": seg["invariants"],
        "SEATS": seats,
        "LAYOUTS": layouts_rel,
        "GROUPS": groups_rel,
        "PIPELINES": pipelines_rel,
    }


